const PORT = process.env.PORT || 5000;

function handleListenError(error) {
  if (error && error.code === "EADDRINUSE") {
    console.error(
      `Port ${PORT} is already in use. Close the other backend window and try again.`
    );
  } else {
    console.error("The server could not start:", safeMessage(error));
  }
  process.exit(1);
}

// The server starts right away. MongoDB connects in the background, so the
// voice interview keeps working even if the database is slow or down.
// In Express 5 the callback receives an error if the server cannot start.
const server = app.listen(PORT, (error) => {
  if (error) {
    handleListenError(error);
    return;
  }

  console.log(`Backend running at http://localhost:${PORT}`);
  connectToDatabase();
});

server.on("error", handleListenError); 
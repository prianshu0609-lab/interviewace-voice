// Copies only the real fields Bolna documents. A missing field becomes null,
// so you can always tell "Bolna did not send it" apart from "empty".
function pickExecution(data) {
  const telephony = data.telephony_data || {};

  return {
    id: data.id ?? null,
    agent_id: data.agent_id ?? null,
    status: data.status ?? null,
    error_message: data.error_message ?? null,
    created_at: data.created_at ?? null,
    updated_at: data.updated_at ?? null,
    conversation_duration: data.conversation_duration ?? null, // seconds
    transcript: data.transcript ?? null, // one text string from Bolna
    summary: data.summary ?? null, // null unless call_summary_enabled is on
    extracted_data: data.extracted_data ?? null, // depends on your agent's extraction prompt
    node_extracted_data: data.node_extracted_data ?? null, // graph agents only
    telephony_data: {
      duration: telephony.duration ?? null,
      hangup_by: telephony.hangup_by ?? null,
      hangup_reason: telephony.hangup_reason ?? null,
      recording_url: telephony.recording_url ?? null,
    },
  };
}

function isNonEmptyString(value) {
  return typeof value === "string" && value.trim() !== "";
}

function isNonEmptyObject(value) {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    Object.keys(value).length > 0
  );
}

function hasContent(value) {
  if (isNonEmptyString(value)) return true;
  if (isNonEmptyObject(value)) return true;
  return typeof value === "number";
}

// Bolna sends 0 or null for duration until the call is finalized.
// Returns a positive number of seconds, or null when there is nothing useful.
function toSeconds(value) {
  const number = Number(value);
  return Number.isFinite(number) && number > 0 ? number : null;
}


// Builds the fields to save. A field is added ONLY when Bolna sent a real
// value, so an incomplete response never erases data saved earlier.
function buildInterviewFields(execution) {
  const fields = { status: execution.status };

  if (isNonEmptyString(execution.agent_id)) {
    fields.agentId = execution.agent_id;
  }
  if (isNonEmptyString(execution.transcript)) {
    fields.transcript = execution.transcript;
  }
  if (isNonEmptyString(execution.summary)) {
    fields.summary = execution.summary;
  }
  if (isNonEmptyString(execution.error_message)) {
    fields.errorMessage = execution.error_message;
  }
  if (isNonEmptyObject(execution.extracted_data)) {
    fields.extractedData = execution.extracted_data;
  }

  const duration =
    toSeconds(execution.conversation_duration) ??
    toSeconds(execution.telephony_data.duration);
  if (duration !== null) {
    fields.duration = duration; // seconds
  }

  return fields;
}

// Upsert: creates the interview the first time, updates it every time after.
// Never throws. It always returns { saved, message }.
async function saveInterview(runId, execution) {
  if (!isDatabaseReady()) {
    return {
      saved: false,
      message: "The database is not connected right now, so this interview was not saved. Request this URL again later.",
    };
  }

  const fields = buildInterviewFields(execution);

  // Two tries: if two requests for the same new Run ID arrive at the very
  // same moment, MongoDB can reject one with a duplicate-key error (11000).
  // Trying once more simply turns it into a normal update.
  for (let attempt = 1; attempt <= 2; attempt += 1) {
    try {
      await Interview.findOneAndUpdate(
        { runId },
        { $set: fields },
        {
          upsert: true,
          runValidators: true,
          setDefaultsOnInsert: true,
        }
      ).lean();

      console.log(`Interview saved: ${runId} (status: ${fields.status})`);
      return { saved: true, message: "Interview saved to history." };
    } catch (error) {
      if (error && error.code === 11000 && attempt === 1) continue;

      console.error(
        `Could not save interview ${runId} (${error.name}):`,
        safeMessage(error)
      );
      return {
        saved: false,
        message: "The interview data was retrieved but could not be saved to the database.",
      };
    }
  }

  return {
    saved: false,
    message: "The interview data was retrieved but could not be saved to the database.",
  };
}

/* ==========================================================================
   Existing endpoint 3: get (and save) the data of an interview
   GET /api/executions/:runId   (behavior and response shape unchanged)
   ========================================================================== */

app.get("/api/executions/:runId", async (req, res) => {
  // Always fetch fresh data, because the call may still be finishing.
  res.set("Cache-Control", "no-store");

  // 1. Validate the Run ID before talking to Bolna.
  //    Lowercase it so the same ID can never be saved twice by letter case.
  const runId = String(req.params.runId || "").trim().toLowerCase();
  if (!UUID_REGEX.test(runId)) {
    return res.status(400).json({
      error: "invalid_run_id",
      message: "The Run ID must be a UUID like b7140255-af33-4608-8e97-04dd944b8e48.",
    });
  }

  // 2. Check that the server has its Bolna credentials.
  const apiKey = process.env.BOLNA_API_KEY;
  const agentId = process.env.BOLNA_AGENT_ID;
  if (!apiKey || !agentId) {
    return res.status(500).json({
      error: "missing_credentials",
      message: "Bolna credentials are missing in server/.env",
    });
  }

  // 3. Ask Bolna for the execution.
  let response;
  try {
    response = await fetch(
      `${BOLNA_API_BASE}/executions/${encodeURIComponent(runId)}`,
      {
        method: "GET",
        headers: {
          Authorization: `Bearer ${apiKey}`,
          Accept: "application/json",
        },
        signal: AbortSignal.timeout(BOLNA_TIMEOUT_MS),
      }
    );
  } catch (error) {
    const timedOut = error.name === "TimeoutError" || error.name === "AbortError";
    console.error("Could not reach Bolna:", error.name, safeMessage(error));

    return res.status(timedOut ? 504 : 502).json({
      error: timedOut ? "bolna_timeout" : "bolna_unreachable",
      message: timedOut
        ? "Bolna took too long to respond. Please try again."
        : "Could not reach Bolna. Check your internet connection and try again.",
    });
  }

  // Read the body safely. It might not be valid JSON.
  let data = null;
  try {
    data = await response.json();
  } catch (error) {
    data = null;
  }

  // 4. Handle error responses from Bolna. Nothing is saved for these.
  if (!response.ok) {
    const bolnaMessage =
      data && typeof data.message === "string" ? data.message : null;

    // Never log the API key. Only the status, Run ID and Bolna's message.
    console.error("Bolna execution error:", response.status, runId, bolnaMessage);

    if (response.status === 401 || response.status === 403) {
      return res.status(502).json({
        error: "bolna_auth_failed",
        message: "Bolna rejected the API key. Check BOLNA_API_KEY in server/.env.",
      });
    }
    if (response.status === 404) {
      return res.status(404).json({
        error: "execution_not_found",
        message: "Bolna has no interview with this Run ID.",
        bolna_message: bolnaMessage,
      });
    }
    if (response.status === 400) {
      return res.status(400).json({
        error: "bolna_rejected_request",
        message: "Bolna rejected this Run ID. It may not exist.",
        bolna_message: bolnaMessage,
      });
    }
    if (response.status === 429) {
      return res.status(429).json({
        error: "bolna_rate_limited",
        message: "Too many requests to Bolna. Wait a moment and try again.",
      });
    }
    return res.status(502).json({
      error: "bolna_unavailable",
      message: `Bolna returned an unexpected error (HTTP ${response.status}).`,
      bolna_message: bolnaMessage,
    });
  }

  // 5. Check that the response looks like an execution. Nothing is saved
  //    before this check passes.
  if (
    !data ||
    typeof data !== "object" ||
    Array.isArray(data) ||
    typeof data.status !== "string"
  ) {
    console.error("Unexpected Bolna response format for Run ID:", runId);
    return res.status(502).json({
      error: "unexpected_response",
      message: "Bolna returned data in a format this server does not recognise.",
    });
  }

  // 6. Only handle interviews that belong to YOUR agent.
  if (data.agent_id && data.agent_id !== agentId) {
    return res.status(404).json({
      error: "execution_not_found",
      message: "This Run ID does not belong to the InterviewAce agent.",
    });
  }

  if (typeof data.id === "string" && data.id.toLowerCase() !== runId) {
    console.warn(`Bolna returned a different execution id than requested (${runId}).`);
  }

  // 7. Build the answer (same fields as before).
  const finished = FINISHED_STATUSES.has(data.status);
  const completed = data.status === "completed";
  const execution = pickExecution(data);

  let message;
  if (completed) {
    message = "Interview data is ready.";
  } else if (finished) {
    message = `The call ended with status "${data.status}". It did not complete normally, so some data may be missing.`;
  } else {
    message =
      "The call is still being processed by Bolna. Wait a few seconds and request this URL again.";
  }

  // 8. Save to MongoDB. This never throws, so a database problem can never
  //    break the response above.
  let storage;
  if (data.agent_id === agentId) {
    storage = await saveInterview(runId, execution);
  } else {
    // Bolna did not report an agent ID, so ownership cannot be verified.
    storage = {
      saved: false,
      message: "Bolna did not report an agent ID, so this interview was not saved.",
    };
  }

  // 200 = Bolna is done with this call. 202 = still processing, try again.
  return res.status(finished ? 200 : 202).json({
    ready: completed,
    finished,
    status: data.status,
    message,
    available: {
      transcript: hasContent(execution.transcript),
      summary: hasContent(execution.summary),
      extracted_data: hasContent(execution.extracted_data),
    },
    storage,
    execution,
  });
});


// Turns any error into a short, safe string. Connection strings and Gemini
// API keys are hidden.
function safeMessage(error) {
  let raw = error && error.message ? String(error.message) : String(error);

  raw = raw.replace(/mongodb(\+srv)?:\/\/\S+/gi, "[hidden]");
  raw = raw.replace(/AIza[0-9A-Za-z_-]{20,}/g, "[hidden]");

  const geminiKey = (process.env.GEMINI_API_KEY || "").trim();
  if (geminiKey) {
    raw = raw.split(geminiKey).join("[hidden]");
  }

  return raw.slice(0, 200);
}


function sendDatabaseUnavailable(res) {
  return res.status(503).json({
    error: "database_unavailable",
    message: "The database is not connected right now. Please try again in a moment.",
  });
}

// Shared by the history routes and the feedback route: connection problems
// become 503, everything else becomes a generic 500. No stack traces or
// details are sent.
function sendHistoryError(res, error, context) {
  console.error(`${context} (${error && error.name}):`, safeMessage(error));

  if (isDatabaseConnectionError(error)) {
    return sendDatabaseUnavailable(res);
  }

  return res.status(500).json({
    error: "database_error",
    message: "Could not read from the database.",
  });
}

// Accepts only whole numbers written with digits, between 1 and max.
// Returns the number, the default when the parameter is absent, or null when invalid.
// A repeated parameter (?limit=1&limit=2) arrives as an array and is rejected.
function parseIntegerParam(raw, defaultValue, max) {
  if (raw === undefined) return defaultValue;
  if (typeof raw !== "string" || !/^\d{1,6}$/.test(raw)) return null;

  const number = parseInt(raw, 10);
  if (number < 1 || number > max) return null;
  return number;
}

/* GET /api/interviews?page=1&limit=10  (newest first) */
app.get("/api/interviews", async (req, res) => {
  res.set("Cache-Control", "no-store");

  const page = parseIntegerParam(req.query.page, 1, MAX_PAGE_NUMBER);
  const limit = parseIntegerParam(req.query.limit, DEFAULT_PAGE_SIZE, MAX_PAGE_SIZE);

  if (page === null || limit === null) {
    return res.status(400).json({
      error: "invalid_pagination",
      message: `page must be a whole number from 1 to ${MAX_PAGE_NUMBER}, and limit a whole number from 1 to ${MAX_PAGE_SIZE}.`,
    });
  }

  if (!isDatabaseReady()) {
    return sendDatabaseUnavailable(res);
  }

  try {
    const [total, interviews] = await Promise.all([
      Interview.countDocuments({}),
      Interview.find({})
        .sort({ createdAt: -1, _id: -1 })
        .skip((page - 1) * limit)
        .limit(limit)
        .select(LIST_FIELDS)
        .lean(),
    ]);

    const totalPages = Math.ceil(total / limit);

    return res.json({
      interviews,
      pagination: {
        total,
        page,
        limit,
        totalPages,
        hasNextPage: page < totalPages,
        hasPrevPage: page > 1,
      },
    });
  } catch (error) {
    return sendHistoryError(res, error, "Could not list interviews");
  }
});

/* GET /api/interviews/:runId  (one saved interview, including transcript) */
app.get("/api/interviews/:runId", async (req, res) => {
  res.set("Cache-Control", "no-store");

  const runId = String(req.params.runId || "").trim().toLowerCase();
  if (!UUID_REGEX.test(runId)) {
    return res.status(400).json({
      error: "invalid_run_id",
      message: "The Run ID must be a UUID like b7140255-af33-4608-8e97-04dd944b8e48.",
    });
  }

  if (!isDatabaseReady()) {
    return sendDatabaseUnavailable(res);
  }

  try {
    const interview = await Interview.findOne({ runId })
      .select("-_id -__v")
      .lean();

    if (!interview) {
      return res.status(404).json({
        error: "interview_not_found",
        message: "No saved interview has this Run ID.",
      });
    }

    return res.json({ interview });
  } catch (error) {
    return sendHistoryError(res, error, `Could not read interview ${runId}`);
  }
});


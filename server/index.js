/* ==========================================================================
   MongoDB connection (one connection, created once, shared by all requests)
   ========================================================================== */

let dbConnecting = false;
let dbRetryDelayMs = DB_RETRY_INITIAL_MS;

function isDatabaseReady() {
  // 1 means "connected". Anything else means we must not pretend it is.
  return mongoose.connection.readyState === 1;
}

// True when an error means "the database cannot be reached" (as opposed to a
// bug or bad data). Used to answer 503 instead of 500.
const DB_CONNECTION_ERROR_NAMES = new Set([
  "MongoNetworkError",
  "MongoNetworkTimeoutError",
  "MongoServerSelectionError",
  "MongooseServerSelectionError",
  "MongoNotConnectedError",
  "MongoTopologyClosedError",
]);

function isDatabaseConnectionError(error) {
  if (!error) return false;
  if (DB_CONNECTION_ERROR_NAMES.has(error.name)) return true;
  return /buffering timed out/i.test(String(error.message || ""));
}

mongoose.connection.on("disconnected", () => {
  console.warn("MongoDB disconnected. The driver will try to reconnect.");
});
mongoose.connection.on("reconnected", () => {
  console.log("MongoDB reconnected.");
});
mongoose.connection.on("error", (error) => {
  console.error("MongoDB error:", error.name, safeMessage(error));
});

async function connectToDatabase() {
  const uri = process.env.MONGODB_URI;

  if (!uri) {
    console.error(
      "MONGODB_URI is missing in server/.env. Interviews will not be saved."
    );
    return;
  }

  // Never start a second connection attempt while one is running or active.
  if (dbConnecting || mongoose.connection.readyState !== 0) return;
  dbConnecting = true;

  try {
    await mongoose.connect(uri, { serverSelectionTimeoutMS: 8000 });
    console.log("MongoDB connected successfully");
    dbRetryDelayMs = DB_RETRY_INITIAL_MS; // success: reset the backoff

    // Make sure the unique index on runId exists. Failure here is not fatal.
    Interview.init().catch((error) => {
      console.error("Could not confirm Interview indexes:", safeMessage(error));
    });
  } catch (error) {
    const delay = dbRetryDelayMs;
    dbRetryDelayMs = Math.min(dbRetryDelayMs * 2, DB_RETRY_MAX_MS);

    console.error(`MongoDB connection failed (${error.name}):`, safeMessage(error));
    console.error(`Retrying in ${delay / 1000} seconds...`);
    setTimeout(connectToDatabase, delay);
  } finally {
    dbConnecting = false;
  }
}

